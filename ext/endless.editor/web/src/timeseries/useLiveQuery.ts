import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { sqlApi } from '../api/sqlApi';
import type { SqlCell, SqlColumn, SqlExecutionResponse, SqlResultSet, VisualizationCapabilities } from '../models/sql';
import { isReadOnlyStatement } from './detect';
import { buildDataset } from './dataset';
import { emptyDataset, type LiveMode, type TimeSeriesDataset, type TimeSeriesMapping, type VisualizationConfig } from './model';

export type LiveStatus = 'idle' | 'running' | 'paused' | 'error' | 'stopped';
const MAX_CONSECUTIVE_FAILURES = 3;

export interface LiveQueryState {
  columns: SqlColumn[]; dataset: TimeSeriesDataset; status: LiveStatus; busy: boolean; lastUpdated: number | null;
  lastError: string | null; refreshes: number; skipped: number; failures: number; truncated: boolean;
  /** SQL generated by the plugin for the most recent server-side fetch, shown to the user. */
  generatedSql: string | null; serverAggregated: boolean; fetchMode: 'full' | 'incremental' | 'aggregate' | null;
}

export interface LiveQueryOptions {
  sessionId: string | null; sql: string; columns: SqlColumn[]; rows: SqlCell[][]; mapping: TimeSeriesMapping | null;
  config: VisualizationConfig; capabilities: VisualizationCapabilities;
}

export interface LiveQueryController {
  state: LiveQueryState; availableModes: LiveMode[]; canRefresh: boolean;
  refresh: () => Promise<void>; start: () => void; pause: () => void; resume: () => void; stop: () => void; cancel: () => Promise<void>;
}

const firstResultSet = (response: SqlExecutionResponse): SqlResultSet | null =>
  response.type === 'resultset' ? response : response.type === 'batch' ? (response.results.find((r) => r.type === 'resultset') as SqlResultSet | undefined) ?? null : null;

const sameRow = (a: SqlCell[], b: SqlCell[]) => a.length === b.length && a.every((cell, i) => JSON.stringify(cell) === JSON.stringify(b[i]));

/**
 * Generic real-time controller. It never re-executes anything but read-only statements, runs at
 * most one request at a time, schedules the next poll only after the previous one settled, and
 * keeps the last good data when a refresh fails.
 */
export function useLiveQuery({ sessionId, sql, columns, rows, mapping, config, capabilities }: LiveQueryOptions): LiveQueryController {
  const readOnly = useMemo(() => isReadOnlyStatement(sql), [sql]);
  const availableModes = useMemo<LiveMode[]>(() => {
    const modes: LiveMode[] = ['manual'];
    if (readOnly) { modes.push('polling'); if (capabilities.supportedLiveModes.includes('streaming')) modes.push('streaming'); }
    return modes;
  }, [readOnly, capabilities.supportedLiveModes]);

  // Raw rows are the source of truth so mapping changes never require a refetch.
  const rowsRef = useRef<SqlCell[][]>(rows);
  const columnsRef = useRef<SqlColumn[]>(columns);
  const lastRawRef = useRef<string | null>(null);
  const inFlight = useRef<AbortController | null>(null);
  const timer = useRef<ReturnType<typeof setTimeout> | undefined>(undefined);
  const alive = useRef(true);
  const statusRef = useRef<LiveStatus>('idle');
  const latest = useRef({ sessionId, sql, mapping, config, capabilities, readOnly });
  latest.current = { sessionId, sql, mapping, config, capabilities, readOnly };

  const build = useCallback((source: SqlCell[][], cols: SqlColumn[], map: TimeSeriesMapping | null, naive: VisualizationConfig['naiveTimezone']) => {
    const dataset = map ? buildDataset(cols, source, map, naive) : emptyDataset();
    lastRawRef.current = dataset.lastRawTime;
    return dataset;
  }, []);

  const [state, setState] = useState<LiveQueryState>(() => ({
    columns, dataset: build(rows, columns, mapping, config.naiveTimezone), status: 'idle', busy: false, lastUpdated: null, lastError: null,
    refreshes: 0, skipped: 0, failures: 0, truncated: false, generatedSql: null, serverAggregated: false, fetchMode: null,
  }));
  const update = useCallback((patch: Partial<LiveQueryState> | ((current: LiveQueryState) => Partial<LiveQueryState>)) => {
    if (!alive.current) return;
    setState((current) => ({ ...current, ...(typeof patch === 'function' ? patch(current) : patch) }));
  }, []);
  const setStatus = useCallback((status: LiveStatus) => { statusRef.current = status; update({ status }); }, [update]);

  // A new execution result (new rows) replaces the buffer; mapping or time-zone changes rebuild from it.
  useEffect(() => { rowsRef.current = rows; columnsRef.current = columns; }, [rows, columns]);
  useEffect(() => {
    update({ columns: columnsRef.current, dataset: build(rowsRef.current, columnsRef.current, mapping, config.naiveTimezone) });
  }, [rows, columns, mapping, config.naiveTimezone, build, update]);

  const clearTimer = () => { if (timer.current !== undefined) { clearTimeout(timer.current); timer.current = undefined; } };

  const refresh = useCallback(async () => {
    const { sessionId: session, sql: statement, mapping: map, config: cfg, capabilities: caps, readOnly: safe } = latest.current;
    if (!session || !safe) return;
    if (inFlight.current) { update((current) => ({ skipped: current.skipped + 1 })); return; }
    const controller = new AbortController();
    inFlight.current = controller;
    update({ busy: true });
    const aggregate = cfg.serverSide && caps.serverSideAggregation && cfg.aggregation !== 'none' && map !== null;
    const incremental = !aggregate && cfg.incremental && caps.incrementalQueries && map !== null && lastRawRef.current !== null && rowsRef.current.length > 0;
    try {
      let resultSet: SqlResultSet | null; let generated: string | null = null; let mode: LiveQueryState['fetchMode'];
      if (aggregate) {
        const response = await sqlApi.timeSeries(session, { sql: statement, timeColumn: map.timeColumn, valueColumns: map.valueColumns, groupColumn: map.groupColumn,
          aggregation: cfg.aggregation as Exclude<typeof cfg.aggregation, 'none'>, intervalSeconds: cfg.intervalSeconds }, controller.signal);
        resultSet = firstResultSet(response.result); generated = response.sql; mode = 'aggregate';
        if (response.result.type === 'error') throw new Error(response.result.error.message);
      } else if (incremental) {
        const response = await sqlApi.timeSeries(session, { sql: statement, timeColumn: map.timeColumn, since: lastRawRef.current, sinceExclusive: false }, controller.signal);
        resultSet = firstResultSet(response.result); generated = response.sql; mode = 'incremental';
        if (response.result.type === 'error') throw new Error(response.result.error.message);
      } else {
        const response = await sqlApi.execute(session, statement, controller.signal);
        if (response.type === 'error') throw new Error(response.error.message);
        resultSet = firstResultSet(response); mode = 'full';
      }
      if (!resultSet) throw new Error('The statement did not return a result set.');
      if (mode === 'incremental') {
        // Inclusive lower bound keeps rows that share the newest timestamp; drop exact duplicates of what we already hold.
        const timeIndex = columnsRef.current.findIndex((column) => column.name === map!.timeColumn);
        const boundary = rowsRef.current.filter((row) => String(row[timeIndex]) === lastRawRef.current);
        const fresh = resultSet.rows.filter((row) => !boundary.some((known) => sameRow(known, row)));
        const merged = rowsRef.current.concat(fresh);
        rowsRef.current = merged.length > cfg.maxRetainedPoints ? merged.slice(merged.length - cfg.maxRetainedPoints) : merged;
      } else {
        rowsRef.current = resultSet.rows.length > cfg.maxRetainedPoints ? resultSet.rows.slice(resultSet.rows.length - cfg.maxRetainedPoints) : resultSet.rows;
        columnsRef.current = resultSet.columns;
      }
      const dataset = build(rowsRef.current, columnsRef.current, map, cfg.naiveTimezone);
      update((current) => ({ columns: columnsRef.current, dataset, lastUpdated: Date.now(), lastError: null, failures: 0, refreshes: current.refreshes + 1,
        truncated: resultSet!.truncated, generatedSql: generated, serverAggregated: mode === 'aggregate', fetchMode: mode }));
    } catch (error) {
      if (controller.signal.aborted) return;
      const message = error instanceof Error ? error.message : 'Refresh failed.';
      update((current) => {
        const failures = current.failures + 1;
        const fatal = /session not found/i.test(message) || failures >= MAX_CONSECUTIVE_FAILURES;
        if (fatal && statusRef.current === 'running') { statusRef.current = 'error'; clearTimer(); }
        return { lastError: message, failures, status: fatal && current.status === 'running' ? 'error' : current.status };
      });
    } finally {
      if (inFlight.current === controller) inFlight.current = null;
      update({ busy: false });
    }
  }, [build, update]);

  const schedule = useCallback(() => {
    clearTimer();
    const seconds = latest.current.config.refreshSeconds;
    if (statusRef.current !== 'running' || seconds <= 0) return;
    timer.current = setTimeout(async () => {
      timer.current = undefined;
      if (statusRef.current !== 'running' || !alive.current) return;
      await refresh();
      schedule();
    }, seconds * 1000);
  }, [refresh]);

  const start = useCallback(() => {
    const mode = latest.current.config.liveMode;
    if (!latest.current.readOnly || mode === 'manual') return;
    if (mode === 'streaming') { update({ lastError: 'Streaming is declared by the plugin but no streaming transport is available in this build.' }); setStatus('error'); return; }
    update({ failures: 0, lastError: null });
    setStatus('running');
    void refresh().then(schedule);
  }, [refresh, schedule, setStatus, update]);
  const pause = useCallback(() => { if (statusRef.current === 'running') { clearTimer(); setStatus('paused'); } }, [setStatus]);
  const resume = useCallback(() => { if (statusRef.current === 'paused' || statusRef.current === 'error') start(); }, [start]);
  const stop = useCallback(() => { clearTimer(); inFlight.current?.abort(); inFlight.current = null; if (statusRef.current !== 'idle') setStatus('stopped'); }, [setStatus]);
  const cancel = useCallback(async () => {
    inFlight.current?.abort(); inFlight.current = null;
    update({ busy: false });
    const { sessionId: session, capabilities: caps } = latest.current;
    if (session && caps.queryCancellation) await sqlApi.cancel(session).catch(() => undefined);
  }, [update]);

  // Refresh interval changes take effect on the next tick; mode changes stop a running loop.
  useEffect(() => { if (statusRef.current === 'running') schedule(); }, [config.refreshSeconds, schedule]);
  useEffect(() => { if (config.liveMode === 'manual' && statusRef.current === 'running') { clearTimer(); setStatus('idle'); } }, [config.liveMode, setStatus]);
  // A different session or statement must never reuse this loop or its in-flight request.
  useEffect(() => () => { clearTimer(); inFlight.current?.abort(); inFlight.current = null; statusRef.current = 'idle'; }, [sessionId, sql]);
  useEffect(() => { alive.current = true; return () => { alive.current = false; clearTimer(); inFlight.current?.abort(); }; }, []);

  return { state, availableModes, canRefresh: Boolean(sessionId) && readOnly, refresh, start, pause, resume, stop, cancel };
}
